#   *-MC: pure Monte Carlo propagation, no maneuver library access. The
#         190-edge bundle is fixed-duration (1.0 s) with discrete actions,
#         so the MC variant uses use_fixed_sampling_time=True and the
#         agent's discrete-action override (apply_discrete_random_action).
#   *-EB: pulls (action, t) directly from the 190-edge bundle (GBRRT paper).
