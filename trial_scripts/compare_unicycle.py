# JIT warm-up: run each planner once with a tiny budget so the first
# real trial doesn't include numba-compilation overhead.
print("Warming up JIT...")
WARMUP_BUDGET = 0.3
def _warmup():
    eb_kw = dict(edge_bundle=eb, eb_kd_tree=kd_tree_eb,
                 get_eb_kd_tree_query=agent.get_eb_kd_tree_query,
                 kd_tree_delta_radius=np.pi,
                 translate_function=agent.kd_tree_point_translate_function)
    eb_sort_kw = dict(eb_kw, sort_edges_function=agent.sort_kd_tree_edges)
    base = dict(start=start, goal_radius=goal_radius, env=env, agent=agent,
                sampling_time_step=T_max, minimum_time_step=0.1,
                max_iter=10000, planning_time=WARMUP_BUDGET,
                isvalid_function=agent.is_new_node_valid, cost_function=agent.get_cost,
                random_point_function=agent.get_random_point,
                reached_goal_function=agent.agent_reached_goal,
                udf_seed=99, print_logs=False)
    g2, g3 = goal[:2], goal
    # RRT-MC
    RRT(**base, goal=g2, use_fixed_sampling_time=True,
        num_extension_trials=40, goal_bias=0.05).plan_path()
    # RRT-EB
    RRT(**base, goal=g2, num_extension_trials=40, goal_bias=0.05, **eb_kw).plan_path()
    # SST-MC
    SST(**base, goal=g2, use_fixed_sampling_time=True, num_extension_trials=40,
        goal_bias=0.05, best_near_radius=5.0).plan_path()
    # SST-EB
    SST(**base, goal=g2, num_extension_trials=40, goal_bias=0.05,
        best_near_radius=5.0, **eb_kw).plan_path()
    # GBRRT-MC
    GBRRT(**base, goal=g3, use_fixed_sampling_time=True,
          num_extension_trials=40, heuristic_radius=7.0, gamma=14.0,
          exploitation_ratio=0.8).plan_path()
    # GBRRT-EB
    GBRRT(**base, goal=g3, num_extension_trials=40, heuristic_radius=7.0,
          gamma=14.0, exploitation_ratio=0.8, **eb_kw).plan_path()
    # BBoE
    BBoE(**base, goal=g3, exploitation_ratio=0.8, heuristic_radius=7.0,
         gamma=14.0, k_bias=0.85, num_skip_edges=5, **eb_sort_kw).plan_path()
    # Db-RRT-F
    DbRRT(**base, goal=g2, max_num_edges_per_node=1000,
          delta_disc=1.0, goal_bias=0.05, **eb_sort_kw).plan_path()
    # Db-RRT-C (bidirectional, idbrrt §IV.D.a + other-tree goal-bias)
